import { chromium } from '../web/node_modules/playwright-core/index.mjs';
import fs from 'node:fs/promises';
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1512,height:1100},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8088');
await page.getByLabel('Senha administrativa',{exact:true}).fill((await fs.readFile(new URL('../var/initial-admin-password',import.meta.url),'utf8')).trim());
await page.getByRole('button',{name:'Entrar no painel'}).click();
await page.getByRole('heading',{name:'Dashboard',exact:true}).waitFor();
await page.getByText(/^\d+\.\d+\.\d+\.\d+$/).first().waitFor({timeout:20000}); // real WAN IPv4 loaded via SSE
await page.screenshot({path:'artifacts/dashboard-desktop.png',fullPage:true});
await page.getByRole('button',{name:'Configurar Wi-Fi'}).click();
await page.getByLabel('Nome da rede (SSID)').waitFor();
