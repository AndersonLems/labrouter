await page.getByRole('button',{name:'Wi-Fi 2.4 GHz',exact:true}).click();
await page.getByText('Um único rádio físico em STA+AP').waitFor();
await page.screenshot({path:'artifacts/wifi-capabilities.png',fullPage:true});
