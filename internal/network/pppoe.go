package network

// PPPoE dialer + simulated BRAS (lab only).
//
//   host (CPE)                          netns lab-bras (BRAS)
//   pppd ── pppoe-wan ══ veth ══ bras0 ── pppoe-server ── pppd (per session)
//   ppp-lab: 100.127.250.x  ◄── IPCP ──  100.127.250.1
//
// Isolation: the dialer uses nodefaultroute, never requests peer DNS and
// disables the global /etc/ppp/ip-up hooks, so host routing/DNS are untouched.
// The BRAS unit creates the namespace/veth itself; `ip netns exec` shows it only
// Dir/bras as /etc/ppp (via /etc/netns/lab-bras/ppp); the sandboxed helper only writes files.

import (
	"context"
	"fmt"
	"lab-router/internal/model"
	"lab-router/internal/system"
	"net"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"time"
)

const (
	BRASNamespace = "lab-bras"
	PPPoEVethCPE  = "pppoe-wan"
	PPPoEVethBRAS = "bras0"
	PPPInterface  = "ppp-lab"
	BRASAddress   = "100.127.250.1"
	BRASPoolStart = "100.127.250.10"
	BRASACName    = "LAB-BRAS"
	brasEtc       = Dir + "/bras" // exposed as /etc/ppp inside the BRAS netns via /etc/netns/lab-bras/ppp
	pppoeOptions  = Dir + "/pppoe.options"
	pppoeLog      = Dir + "/pppoe.log"
	brasEnv       = Dir + "/bras.env"
)

func PPPoEOptions(c model.Config) string {
	p := c.PPPoE
	mru := p.MRU
	if mru == 0 {
		mru = 1492
	}
	lines := []string{
		"# Generated by LAB Router — PPPoE dialer towards the simulated BRAS",
		"plugin pppoe.so",
		"nic-" + PPPoEVethCPE,
		"ifname " + PPPInterface,
		"user " + p.Username,
		"password " + p.Password,
		"noauth", "noipdefault", "nodefaultroute", "noproxyarp",
		"persist", "maxfail 0", "holdoff 5",
		"pppoe-padi-timeout 3", "pppoe-padi-attempts 3", // report ERROR_NO_ANSWER in ~20 s, not ~45 s
		"lcp-echo-interval 10", "lcp-echo-failure 3",
		fmt.Sprintf("mru %d", mru), fmt.Sprintf("mtu %d", mru),
		"ip-up-script /bin/true", "ip-down-script /bin/true", // never run global hooks (DNS/routes)
		"noipv6", // IPv4-only lab link; also keeps /etc/ppp/ipv6-up hooks from running
		"logfile " + pppoeLog,
	}
	if p.ServiceName != "" {
		lines = append(lines, "rp_pppoe_service "+p.ServiceName)
	}
	return strings.Join(lines, "\n") + "\n"
}

func BRASSecrets(c model.Config) string {
	s := "# Generated by LAB Router — simulated BRAS accounts\n"
	for _, a := range c.BRAS.Accounts {
		s += fmt.Sprintf("\"%s\" * \"%s\" *\n", a.Username, a.Password)
	}
	return s
}

func BRASServerOptions() string {
	return strings.Join([]string{"require-chap", "lcp-echo-interval 10", "lcp-echo-failure 3", "ms-dns " + BRASAddress, "noipdefault", "nodefaultroute", "mru 1492", "mtu 1492"}, "\n") + "\n"
}

func BRASEnv(c model.Config) string {
	args := fmt.Sprintf("-I %s -L %s -R %s -N 20 -C %s -O /etc/ppp/pppoe-server-options -X /run/lab-router-bras/pppoe-server.pid", PPPoEVethBRAS, BRASAddress, BRASPoolStart, BRASACName)
	if c.BRAS.ServiceName != "" {
		args += " -S " + c.BRAS.ServiceName
	}
	return "BRAS_ARGS=" + args + "\n"
}

// applyPPPoE starts/stops the BRAS and dialer; restarts only what changed.
func applyPPPoE(old model.Config, hasOld bool, c model.Config) error {
	if !c.PPPoE.Enabled {
		return call("systemctl", "stop", "lab-router-pppoe.service", "lab-router-bras.service")
	}
	if e := os.MkdirAll(brasEtc, 0700); e != nil {
		return e
	}
	for name, body := range map[string]string{"chap-secrets": BRASSecrets(c), "pap-secrets": BRASSecrets(c), "pppoe-server-options": BRASServerOptions()} {
		if e := atomic(filepath.Join(brasEtc, name), []byte(body)); e != nil {
			return e
		}
	}
	if e := atomic(brasEnv, []byte(BRASEnv(c))); e != nil {
		return e
	}
	if e := atomic(pppoeOptions, []byte(PPPoEOptions(c))); e != nil {
		return e
	}
	// Accounts are read per authentication, so only Service-Name changes restart the BRAS.
	if !hasOld || old.BRAS.ServiceName != c.BRAS.ServiceName || system.Service("lab-router-bras.service") != "active" {
		if e := call("systemctl", "restart", "lab-router-bras.service"); e != nil {
			return fmt.Errorf("iniciar BRAS simulado: %w", e)
		}
	}
	if !hasOld || old.PPPoE != c.PPPoE || system.Service("lab-router-pppoe.service") != "active" {
		atomic(pppoeLog, nil) // fresh log so LastConnectionError reflects this attempt
		if e := call("systemctl", "restart", "lab-router-pppoe.service"); e != nil {
			return fmt.Errorf("iniciar discador PPPoE: %w", e)
		}
	}
	return nil
}

// PPPoEStatus is reported by the helper (root) and mapped to TR-098 by the CWMP agent.
type PPPoEStatus struct {
	Enabled       bool   `json:"enabled"`
	State         string `json:"state"` // TR-098 ConnectionStatus
	LocalIP       string `json:"local_ip"`
	RemoteIP      string `json:"remote_ip"`
	LastError     string `json:"last_error"` // TR-098 LastConnectionError
	Detail        string `json:"detail"`
	UptimeSeconds int64  `json:"uptime_seconds"`
	MRU           int    `json:"mru"`
	ACName        string `json:"ac_name"`
	MAC           string `json:"mac"`
	RxBytes       uint64 `json:"rx_bytes"`
	TxBytes       uint64 `json:"tx_bytes"`
	RxPackets     uint64 `json:"rx_packets"`
	TxPackets     uint64 `json:"tx_packets"`
}

func counter(iface, name string) uint64 {
	v, _ := strconv.ParseUint(system.Read("/sys/class/net/"+iface+"/statistics/"+name), 10, 64)
	return v
}

// classifyPPPLog maps the latest pppd log events to a TR-098 LastConnectionError.
func classifyPPPLog(log string) (code, detail string) {
	lines := strings.Split(strings.TrimSpace(log), "\n")
	for i := len(lines) - 1; i >= 0; i-- {
		l := strings.TrimSpace(lines[i])
		switch {
		case strings.Contains(l, "local  IP address"):
			return "ERROR_NONE", ""
		case strings.Contains(l, "authentication failed"):
			return "ERROR_AUTHENTICATION_FAILURE", l
		case strings.Contains(l, "Timeout waiting for PADO"), strings.Contains(l, "Timeout waiting for PADS"), strings.Contains(l, "Unable to complete PPPoE Discovery"):
			return "ERROR_NO_ANSWER", l
		case strings.Contains(l, "No response to") && strings.Contains(l, "echo-requests"):
			return "ERROR_ISP_TIME_OUT", l
		case strings.Contains(l, "LCP terminated by peer"), strings.Contains(l, "Modem hangup"), strings.Contains(l, "PADT"):
			return "ERROR_ISP_DISCONNECT", l
		case strings.Contains(l, "IPCP") && strings.Contains(l, "timeout"):
			return "ERROR_IP_CONFIGURATION", l
		}
	}
	return "ERROR_NONE", ""
}

func ReadPPPoEStatus(c model.Config) PPPoEStatus {
	s := PPPoEStatus{Enabled: c.PPPoE.Enabled, State: "Disconnected", LastError: "ERROR_NONE"}
	if !c.PPPoE.Enabled {
		s.State = "Unconfigured"
		return s
	}
	if i, e := net.InterfaceByName(PPPoEVethCPE); e == nil {
		s.MAC = i.HardwareAddr.String()
	}
	log := system.Read(pppoeLog)
	s.LastError, s.Detail = classifyPPPLog(log)
	if strings.Contains(log, "PADO") || strings.Contains(log, "Access-Concentrator") {
		s.ACName = BRASACName
	}
	if system.Service("lab-router-pppoe.service") != "active" {
		return s
	}
	s.State = "Connecting"
	i, e := net.InterfaceByName(PPPInterface)
	if e != nil {
		return s
	}
	addrs, _ := i.Addrs()
	for _, a := range addrs {
		if n, ok := a.(*net.IPNet); ok && n.IP.To4() != nil {
			s.LocalIP = n.IP.String()
		}
	}
	if s.LocalIP == "" {
		return s
	}
	s.State, s.LastError, s.Detail, s.MRU, s.ACName = "Connected", "ERROR_NONE", "", i.MTU, BRASACName
	out, _ := system.Run(context.Background(), "ip", "-4", "-o", "addr", "show", "dev", PPPInterface)
	if f := strings.Fields(out); len(f) > 0 {
		for k, v := range f {
			if v == "peer" && k+1 < len(f) {
				s.RemoteIP = strings.Split(f[k+1], "/")[0]
			}
		}
	}
	if st, e := os.Stat("/run/" + PPPInterface + ".pid"); e == nil {
		s.UptimeSeconds = int64(time.Since(st.ModTime()).Seconds())
	}
	s.RxBytes, s.TxBytes = counter(PPPInterface, "rx_bytes"), counter(PPPInterface, "tx_bytes")
	s.RxPackets, s.TxPackets = counter(PPPInterface, "rx_packets"), counter(PPPInterface, "tx_packets")
	return s
}
